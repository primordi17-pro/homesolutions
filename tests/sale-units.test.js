const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html','utf8');
const block = html.match(/\/\* UNIT_MEASURE_HELPERS_START \*\/([\s\S]*?)\/\* UNIT_MEASURE_HELPERS_END \*\//);
assert.ok(block,'Unit helper block must exist');
const api = new Function(block[1] + '\nreturn {parseSaleUnitsText,getProductSaleUnits,toBaseQuantity,validInventoryQuantity};')();
const units = api.parseSaleUnitsText('Saco | 25 | 6.50\\nCaja | 1.44 | 8.00\\nRollo | 100', 'kg', 0.20);
assert.deepEqual(units.map(u=>[u.name,u.factor,u.price,u.automatic]),[['Saco',25,6.5,false],['Caja',1.44,8,false],['Rollo',100,null,true]]);
const product={baseUnit:'kg',salePrice:0.2,saleUnits:units};
assert.equal(api.getProductSaleUnits(product)[1].price,6.5);
const autoProduct={baseUnit:'kg',salePrice:10,saleUnits:api.parseSaleUnitsText('Saco | 10 |\\nPaquete | 5 | 45','kg',10)};
assert.equal(api.getProductSaleUnits(autoProduct)[1].price,100,'blank presentation price is proportional to base price');
assert.equal(api.getProductSaleUnits(autoProduct)[2].price,45,'manual presentation price remains custom');
assert.equal(api.toBaseQuantity(4,25),100);
assert.equal(api.toBaseQuantity(2.5,1.44),3.6);
assert.equal(api.toBaseQuantity(0.75,100),75);
assert.equal(api.validInventoryQuantity(0.125),true);
assert.equal(api.validInventoryQuantity(0),false);
assert.throws(()=>api.parseSaleUnitsText('Saco | 0 | 4','kg',1));
assert.throws(()=>api.parseSaleUnitsText('kg | 5 | 10','kg',1));
assert.throws(()=>api.parseSaleUnitsText('Saco | 5 | -1','kg',1));
assert.match(html,/saleUnitName:type==='Salida'\?mov\.saleUnit\.name/,'Movement should persist commercial unit metadata');
assert.match(html,/lotAllocations:fifo\.allocations/,'Sale must preserve FIFO lot allocations');
assert.match(html,/saleEnteredQuantity:entered/,'Sale should keep the entered presentation quantity');
console.log('Sales-unit tests passed: parsing, validation, conversion, fractional quantities and FIFO metadata.');
